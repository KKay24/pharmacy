async function importInventory() {
  try {
    await sequelize.authenticate();
    console.log('Database connected.');

    // Split raw data by lines and filter out empty lines
    const lines = rawData.split('\n').map(l => l.trim()).filter(l => l.length > 0);
    const chunkSize = 7; // Number of lines per item

    console.log(`Found ${lines.length} lines of data.`);

    for (let i = 0; i < lines.length; i += chunkSize) {
      if (i + chunkSize > lines.length) break;

      const name = lines[i];
      const supplier = lines[i + 1];
      const initialQty = lines[i + 2]; // Looks like 0 or pre-existing count? ignored for batch?
      const orderQty = parseFloat(lines[i + 3]);
      const costPrice = parseFloat(lines[i + 4]);
      // const totalCost = lines[i+5]; // calculated
      const expiryRaw = lines[i + 6];

      // Clean up date string if needed (some have time ' 0:00:00')
      const expiryDate = expiryRaw.split(' ')[0]; 

      console.log(`Processing: ${name}`);

      // 1. Find or Create Medicine
      let medicine = await Medicine.findOne({ where: { name } });

      if (!medicine) {
        medicine = await Medicine.create({
          name,
          supplier,
          // Defaults
          lowStockThreshold: 10,
          totalQuantity: 0
        });
        console.log(`  - Created new Medicine: ${name}`);
      } else {
        console.log(`  - Found existing Medicine: ${name}`);
      }

      // 2. Create Batch
      // Generate a simple batch number if none provided (using date + random)
      const batchNumber = `BATCH-${Date.now()}-${Math.floor(Math.random() * 1000)}`;

      if (orderQty > 0) {
        await Batch.create({
          medicineId: medicine.id,
          batchNumber: batchNumber,
          quantity: orderQty,
          expiryDate: expiryDate,
          costPrice: costPrice,
          sellingPrice: 0, // Not provided in data, setting to 0 to be updated later
        });
        console.log(`  - Added Batch: ${orderQty} units, Expiry: ${expiryDate}`);
      }
    }

    console.log('Import completed successfully.');

  } catch (error) {
    console.error('Import Error:', error);
  } finally {
    // await sequelize.close(); // Keep open if needed, or close
    process.exit();
  }
}

